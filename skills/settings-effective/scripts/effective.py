# --------------------------------------------------------------------------- model

@dataclass
class Layer:
    name: str                 # managed | cli | local | project | user | global
    path: str
    data: dict = field(default_factory=dict)
    present: bool = False
    error: str = ""           # invalid JSON etc. -> the file is skipped, like the harness does


@dataclass
class Entry:
    key: str                  # dotted leaf path, e.g. permissions.allow, env.FOO
    value: Any
    source: str               # layer name that decided it (or "merged" for lists)
    sources: list[str] = field(default_factory=list)   # for lists: layer per element, aligned
    shadowed: list[dict] = field(default_factory=list)  # [{layer, value}] that lost


@dataclass
class Finding:
    severity: str             # error | warn | info
    key: str
    layer: str
    message: str


@dataclass
class Report:
    project: str
    layers: list[Layer] = field(default_factory=list)
    trusted: bool | None = None
    legacy_allowed_tools: list[str] = field(default_factory=list)
    entries: list[Entry] = field(default_factory=list)
    findings: list[Finding] = field(default_factory=list)
    index_date: str = INDEX_DATE


# --------------------------------------------------------------------------- loading

def read_json(p: Path) -> tuple[dict, str]:
    try:
        text = p.read_text(encoding="utf-8-sig")
    except FileNotFoundError:
        return {}, ""
    except OSError as e:
        return {}, f"unreadable: {e.strerror}"
    try:
        d = json.loads(text)
    except ValueError as e:
        return {}, f"invalid JSON: {e}"
    if not isinstance(d, dict):
        return {}, "top level is not an object"
    return d, ""


def project_dir(start: Path) -> Path:
    """cwd if it has a .claude/, else the nearest ancestor with one, else cwd."""
    start = start.resolve()
    for p in [start, *start.parents]:
        if (p / ".claude").is_dir():
            return p
        if (p / ".git").exists():
            break
    return start


def managed_layer(managed_dir: Path) -> Layer:
    base = managed_dir / "managed-settings.json"
    dropins = sorted(p for p in (managed_dir / "managed-settings.d").glob("*.json")
                     if not p.name.startswith(".")) if (managed_dir / "managed-settings.d").is_dir() else []
    layer = Layer("managed", str(base))
    parts: list[tuple[Path, dict]] = []
    errors = []
    for p in [base, *dropins]:
        d, err = read_json(p)
        if err:
            errors.append(f"{p.name}: {err}")
        elif p.exists():
            parts.append((p, d))
    if not parts and not errors:
        return layer
    layer.present = bool(parts)
    layer.error = "; ".join(errors)
    merged: dict = {}
    for _, d in parts:                       # file first, then drop-ins alphabetically
        merged = merge_two(merged, d)
    layer.data = merged
    if dropins:
        layer.path = f"{base} + managed-settings.d/ ({len(dropins)})"
    return layer


def cli_layer(arg: str | None) -> Layer:
    layer = Layer("cli", "--settings")
    if not arg:
        return layer
    p = Path(arg)
    if p.is_file():
        layer.path = f"--settings {p}"
        layer.data, layer.error = read_json(p)
        layer.present = not layer.error
    else:
        try:
            d = json.loads(arg)
            layer.data, layer.present = (d if isinstance(d, dict) else {}), isinstance(d, dict)
            layer.path = "--settings (inline JSON)"
            if not layer.present:
                layer.error = "top level is not an object"
        except ValueError as e:
            layer.error = f"invalid JSON: {e}"
    return layer


def file_layer(name: str, p: Path) -> Layer:
    layer = Layer(name, str(p))
    layer.data, layer.error = read_json(p)
    layer.present = p.exists() and not layer.error
    return layer


def global_layer(claude_json: Path) -> tuple[Layer, dict]:
    """Only the index's 'Global config' keys count as settings; the rest is state."""
    raw, err = read_json(claude_json)
    layer = Layer("global", str(claude_json))
    layer.error = err
    layer.present = bool(raw) and not err
    layer.data = {k: v for k, v in raw.items()
                  if SETTINGS_INDEX.get(k, ("",))[0] == "Global config"}
    return layer, raw


# --------------------------------------------------------------------------- merging

def merge_two(low: dict, high: dict) -> dict:
    """high wins per leaf; lists union; objects recurse."""
    out = dict(low)
    for k, v in high.items():
        if k in out and isinstance(out[k], dict) and isinstance(v, dict):
            out[k] = merge_two(out[k], v)
        elif k in out and isinstance(out[k], list) and isinstance(v, list) and k not in WHOLE_VALUE:
            out[k] = out[k] + [x for x in v if x not in out[k]]
        else:
            out[k] = v
    return out


def leaves(d: dict, prefix: str = "") -> list[tuple[str, Any]]:
    out = []
    for k, v in d.items():
        key = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict) and v and not _atomic(key):
            out.extend(leaves(v, key))
        else:
            out.append((key, v))
    return out


def _atomic(key: str) -> bool:
    # Objects that are one value, not a bag of keys: mixing statusLine.type from one
    # file with statusLine.command from another would describe nothing real.
    return key.split(".")[0] in ("statusLine", "agent", "modelPicker")


def top_key(key: str) -> str:
    return key.split(".")[0]


def index_scope(key: str) -> str | None:
    """Scope for the most specific index entry covering this dotted key."""
    parts = key.split(".")
    while parts:
        hit = SETTINGS_INDEX.get(".".join(parts))
        if hit:
            return hit[0]
        parts.pop()
    return None


def resolve(layers: list[Layer], findings: list[Finding]) -> list[Entry]:
    """Walk layers from lowest to highest precedence, recording who set each leaf."""
    by_layer = {l.name: l for l in layers}
    order = sorted((l for l in layers if l.present), key=lambda l: -RANK[l.name])  # user -> managed
    table: dict[str, Entry] = {}
    for layer in order:
        for key, value in leaves(layer.data):
            allowed = SCOPE_LAYERS.get(index_scope(key) or "Any file", SCOPE_LAYERS["Any file"])
            if layer.name not in allowed:
                scope = index_scope(key)
                findings.append(Finding("error", key, layer.name,
                                        f"ignored here: scope is '{scope}', set it in "
                                        f"{' / '.join(LABEL[x] for x in sorted(allowed, key=RANK.get))}"))
                continue
            if top_key(key) not in SETTINGS_INDEX and index_scope(key) is None and layer.name != "global":
                near = difflib.get_close_matches(top_key(key), SETTINGS_INDEX, n=1, cutoff=0.75)
                hint = f" - did you mean '{near[0]}'?" if near else ""
                findings.append(Finding("warn", key, layer.name, f"not a known settings key{hint}"))
            prev = table.get(key)
            if prev is None:
                table[key] = Entry(key, value, layer.name,
                                   [layer.name] * len(value) if isinstance(value, list) else [])
            elif isinstance(prev.value, list) and isinstance(value, list) and top_key(key) not in WHOLE_VALUE:
                for x in value:
                    if x not in prev.value:
                        prev.value.append(x)
                        prev.sources.append(layer.name)
                    else:
                        findings.append(Finding("info", key, layer.name,
                                                f"{json.dumps(x)} already listed by {LABEL[prev.sources[prev.value.index(x)]]}"))
                prev.source = "merged" if len(set(prev.sources)) > 1 else prev.source
            else:
                if prev.value != value:
                    prev.shadowed.append({"layer": prev.source, "value": prev.value})
                    findings.append(Finding("info", key, prev.source,
                                            f"{LABEL[prev.source]} sets {json.dumps(prev.value)[:40]} but "
                                            f"{LABEL[layer.name]} wins with {json.dumps(value)[:40]}"))
                prev.value, prev.source = value, layer.name
                prev.sources = [layer.name] * len(value) if isinstance(value, list) else []
    apply_strict_exceptions(table, layers, findings)
    return [table[k] for k in sorted(table)]


def apply_strict_exceptions(table: dict[str, Entry], layers: list[Layer], findings: list[Finding]) -> None:
    """The docs' 'stricter value from a lower scope wins' table."""
    vals = {l.name: dict(leaves(l.data)) for l in layers if l.present}

    def honor(key: str, from_layers: set[str], pick) -> None:
        cands = [(n, v[key]) for n, v in vals.items() if key in v and n in from_layers]
        if not cands or key not in table:
            return
        winner = pick(cands)
        if winner and winner[1] != table[key].value:
            e = table[key]
            # the plain "X wins" note for this key is wrong now; the exception reverses it
            findings[:] = [f for f in findings if not (f.key == key and f.layer == winner[0] and "wins with" in f.message)]
            findings.append(Finding("info", key, winner[0],
                                    f"security key: {LABEL[winner[0]]}'s stricter {json.dumps(winner[1])} is honored over "
                                    f"{LABEL[e.source]}'s {json.dumps(e.value)}"))
            e.shadowed.append({"layer": e.source, "value": e.value})
            e.value, e.source = winner[1], winner[0]

    anyf = {"managed", "cli", "local", "project", "user"}
    honor("disableClaudeAiConnectors", anyf, lambda c: next((x for x in c if x[1] is True), None))
    honor("isolatePeerMachines", anyf, lambda c: next((x for x in c if x[1] is True), None))
    honor("enableArtifact", anyf, lambda c: next((x for x in c if x[1] is False), None))
    honor("disableArtifact", anyf, lambda c: next((x for x in c if x[1] is True), None))
    honor("remoteControlAtStartup", {"project", "local"}, lambda c: next((x for x in c if x[1] is False), None))
    for k in ("useAutoModeDuringPlan", "syncClaudeAiSkills", "syncClaudeAiPlugins"):
        honor(k, {"managed", "cli", "user", "local"}, lambda c: next((x for x in c if x[1] is False), None))
    honor("maxEffortLevel", anyf,
          lambda c: min((x for x in c if x[1] in EFFORT_ORDER), key=lambda x: EFFORT_ORDER.index(x[1]), default=None))
    honor("crossSessionInbound", {"project", "local"},
          lambda c: max((x for x in c if x[1] in INBOUND_ORDER), key=lambda x: INBOUND_ORDER.index(x[1]), default=None))


# --------------------------------------------------------------------------- permissions

RULE = re.compile(r"^(?P<tool>[A-Za-z_][\w-]*)(?:\((?P<spec>.*)\))?$")


def permission_findings(entries: dict[str, Entry], findings: list[Finding], trusted: bool | None) -> None:
    lists = {k: entries.get(f"permissions.{k}") for k in ("allow", "ask", "deny")}
    deny = set(lists["deny"].value) if lists["deny"] else set()
    ask = set(lists["ask"].value) if lists["ask"] else set()
    if lists["allow"]:
        for rule, src in zip(lists["allow"].value, lists["allow"].sources):
            if rule in deny:
                findings.append(Finding("warn", "permissions.allow", src,
                                        f"{json.dumps(rule)} is allowed here but denied elsewhere - deny wins"))
            elif rule in ask:
                findings.append(Finding("warn", "permissions.allow", src,
                                        f"{json.dumps(rule)} is allowed here but an ask rule for it exists - ask wins, you will still be prompted"))
            if not RULE.match(rule):
                findings.append(Finding("warn", "permissions.allow", src, f"{json.dumps(rule)} is not Tool or Tool(spec) shaped"))
        if trusted is False and any(s == "project" for s in lists["allow"].sources):
            findings.append(Finding("warn", "permissions.allow", "project",
                                    "project allow rules apply only after you trust this folder; it is not trusted yet"))
    for k in ("ask", "deny"):
        e = lists[k]
        if e:
            for rule, src in zip(e.value, e.sources):
                if not RULE.match(rule):
                    findings.append(Finding("warn", f"permissions.{k}", src, f"{json.dumps(rule)} is not Tool or Tool(spec) shaped"))
    mode = entries.get("permissions.defaultMode")
    if mode and mode.value == "bypassPermissions":
        dis = entries.get("permissions.disableBypassPermissionsMode")
        if dis and dis.value == "disable":
            findings.append(Finding("warn", "permissions.defaultMode", mode.source,
                                    f"bypassPermissions requested but {LABEL[dis.source]} disables bypass mode"))


# --------------------------------------------------------------------------- hooks / env

def hook_rows(entries: list[Entry]) -> list[tuple[str, str, str, str]]:
    """(event, matcher, command-or-type, source) for every hook handler."""
    rows = []
    for e in entries:
        if not e.key.startswith("hooks.") or not isinstance(e.value, list):
            continue
        event = e.key.split(".", 1)[1]
        for group, src in zip(e.value, e.sources):
            if not isinstance(group, dict):
                continue
            matcher = group.get("matcher", "*") or "*"
            for h in group.get("hooks", []) or []:
                if isinstance(h, dict):
                    what = h.get("command") or h.get("url") or h.get("prompt") or h.get("type", "?")
                    rows.append((event, str(matcher), str(what), src))
    return rows


def env_findings(entries: dict[str, Entry], findings: list[Finding], trusted: bool | None) -> None:
    for e in entries.values():
        if not e.key.startswith("env."):
            continue
        var = e.key[4:]
        shell = os.environ.get(var)
        if shell is not None and str(shell) != str(e.value):
            findings.append(Finding("info", e.key, e.source,
                                    f"also exported in your shell as {json.dumps(shell)[:40]}; which applies is decided per variable"))
        if trusted is False and e.source == "project":
            findings.append(Finding("warn", e.key, "project", "project env applies only after you trust this folder"))


# --------------------------------------------------------------------------- report

def short(v: Any, width: int) -> str:
    s = v if isinstance(v, str) and v.strip() else json.dumps(v, ensure_ascii=False)
    return s if len(s) <= width else s[: width - 1] + "…"


def render(rep: Report, a) -> None:
    W = 200 if a.full else 48
    print(f"settings-effective  {rep.project}")
    print()
    for l in sorted(rep.layers, key=lambda l: RANK[l.name]):
        state = "loaded" if l.present else ("SKIPPED" if l.error else "absent")
        line = f"  {LABEL[l.name]:15} {state:8} {l.path}"
        if l.error:
            line += f"   <- {l.error}"
        print(line)
    if rep.trusted is None:
        print(f"  {'trust':15} {'unknown':8} no entry for this project in ~/.claude.json (never opened here?)")
    else:
        print(f"  {'trust':15} {'yes' if rep.trusted else 'NO':8} ~/.claude.json projects entry"
              + ("" if rep.trusted else "   <- project allow rules, env and marketplaces wait for trust"))
    if rep.legacy_allowed_tools:
        print(f"  {'allowedTools':15} {len(rep.legacy_allowed_tools):<8} legacy per-project allow list in ~/.claude.json")
    if rep.index_date:
        print(f"  {'index':15} {'':8} {len(SETTINGS_INDEX)} keys from the docs, {rep.index_date}")

    entries = rep.entries
    if a.key:
        entries = [e for e in entries if e.key == a.key or e.key.startswith(a.key + ".")]
    if not a.problems_only:
        print()
        if not entries:
            print("  (no effective keys" + (f" under {a.key}" if a.key else "") + ")")
        for e in entries:
            if isinstance(e.value, list):
                itemize = a.full or a.key or e.key.startswith(("permissions.", "hooks."))
                if itemize and not e.key.startswith("hooks."):
                    print(f"  {e.key:44} [{len(e.value)}]")
                    for v, s in zip(e.value, e.sources):
                        print(f"    {short(v, W + 30):74}  {LABEL[s]}")
                else:
                    srcs = ", ".join(LABEL[s] for s in dict.fromkeys(e.sources))
                    n = len(e.value)
                    count = f"[{n} {'entry' if n == 1 else 'entries'}]"
                    print(f"  {e.key:44} {count:{W}}  {srcs}")
            else:
                print(f"  {e.key:44} {short(e.value, W):{W}}  {LABEL[e.source]}")
        rows = hook_rows(entries)
        if rows:
            print()
            print(f"hooks     {len(rows)} handler{'s' if len(rows) != 1 else ''}")
            for ev, m, what, src in rows:
                print(f"  {ev:20} {m:24} {short(what, 60):60}  {LABEL[src]}")

    fs = rep.findings
    if a.key:
        fs = [f for f in fs if f.key == a.key or f.key.startswith(a.key + ".")]
    sev = {"error": 0, "warn": 0, "info": 0}
    for f in fs:
        sev[f.severity] += 1
    print()
    print(f"findings  {sev['error']} ignored, {sev['warn']} warnings, {sev['info']} notes")
    for f in sorted(fs, key=lambda f: ({"error": 0, "warn": 1, "info": 2}[f.severity], f.key)):
        tag = {"error": "IGNORED", "warn": "warn", "info": "note"}[f.severity]
        print(f"  {tag:8} {f.key:40} {LABEL.get(f.layer, f.layer):12} {f.message}")


def explain(key: str) -> int:
    hit = SETTINGS_INDEX.get(key)
    if not hit:
        near = difflib.get_close_matches(key, SETTINGS_INDEX, n=5, cutoff=0.5)
        print(f"{key}: not in the settings index" + (f"; near: {', '.join(near)}" if near else ""))
        return 1
    scope, topic, desc = hit
    layers = SCOPE_LAYERS.get(scope, set())
    print(f"{key}")
    print(f"  {desc}")
    print(f"  topic   {topic}")
    print(f"  scope   {scope}  ->  {', '.join(LABEL[x] for x in sorted(layers, key=RANK.get))}")
    if key in WHOLE_VALUE:
        print("  merge   taken whole from the highest layer that sets it (not merged as a list)")
    if key in RESTART_ONLY:
        print("  note    read at session start; an edit does not reach a running session")
    subs = [k for k in SETTINGS_INDEX if k.startswith(key + ".")]
    if subs:
        print(f"  subkeys {', '.join(subs)}")
    return 0


