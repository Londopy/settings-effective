def build(a) -> Report:
    claude_home = Path(a.claude_home)
    proj = project_dir(Path(a.project))
    rep = Report(project=str(proj))
    managed_dir = Path(a.managed_dir) if a.managed_dir else MANAGED_DIRS.get(sys.platform, MANAGED_DIRS["linux"])
    glayer, raw_global = global_layer(Path(a.claude_json) if a.claude_json else Path.home() / ".claude.json")
    rep.layers = [
        managed_layer(managed_dir),
        cli_layer(a.settings),
        file_layer("local", proj / ".claude" / "settings.local.json"),
        file_layer("project", proj / ".claude" / "settings.json"),
        file_layer("user", claude_home / "settings.json"),
        glayer,
    ]
    pentry = (raw_global.get("projects") or {}).get(str(proj)) or {}
    if not pentry:                                  # the harness keys this by the path it saw
        for k, v in (raw_global.get("projects") or {}).items():
            try:
                if Path(k).resolve() == proj:
                    pentry = v
                    break
            except OSError:
                pass
    if pentry:
        rep.trusted = bool(pentry.get("hasTrustDialogAccepted"))
        rep.legacy_allowed_tools = list(pentry.get("allowedTools") or [])
    for l in rep.layers:
        if l.error:
            rep.findings.append(Finding("error", "(file)", l.name, f"{l.error} - the whole file is skipped"))
    rep.entries = resolve(rep.layers, rep.findings)
    by_key = {e.key: e for e in rep.entries}
    permission_findings(by_key, rep.findings, rep.trusted)
    env_findings(by_key, rep.findings, rep.trusted)
    for e in rep.entries:
        if top_key(e.key) in RESTART_ONLY:
            rep.findings.append(Finding("info", e.key, e.source, "read at session start only; use /model or /effort to change it mid-session"))
    if by_key.get("disableAllHooks", Entry("", False, "")).value is True and any(e.key.startswith("hooks.") for e in rep.entries):
        rep.findings.append(Finding("warn", "hooks", by_key["disableAllHooks"].source, "disableAllHooks is true - none of the hooks below run"))
    return rep


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0], formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", default=os.getcwd(), help="project directory (default: cwd; walks up to a .claude/ or the git root)")
    ap.add_argument("--settings", default=None, help="a JSON file or string, as `claude --settings` would take")
    ap.add_argument("--key", default=None, help="only this key / subtree, itemized")
    ap.add_argument("--explain", default=None, metavar="KEY", help="describe a key from the settings index")
    ap.add_argument("--problems-only", action="store_true", help="findings only, no table")
    ap.add_argument("--full", action="store_true", help="itemize every list and do not truncate values")
    ap.add_argument("--strict", action="store_true", help="exit 1 on any error-level finding")
    ap.add_argument("--json", action="store_true", help="machine-readable output")
    ap.add_argument("--claude-home", default=str(Path.home() / ".claude"), help=argparse.SUPPRESS)
    ap.add_argument("--claude-json", default=None, help=argparse.SUPPRESS)
    ap.add_argument("--managed-dir", default=None, help=argparse.SUPPRESS)
    a = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    if a.explain:
        return explain(a.explain)
    rep = build(a)
    if a.json:
        print(json.dumps(asdict(rep), indent=2, default=str))
    else:
        render(rep, a)
    if a.strict and any(f.severity == "error" for f in rep.findings):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
